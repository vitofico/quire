import { english, interpolate, type Translate } from "./translation";
import { useEffect, useState } from "react";
import "./discovery.css";
import {
  type DiscoveryRequest, type Insight, type InsightIdentity, type InsightMetadata,
  discoveryJson, insightBundle, insightIdentity, isHttpStatus, jsonBody, publicLink, rememberPreview,
  promotePreview, translateRequestMessage,
} from "./api";
import { missingProvider, refreshAiState, useAiState } from "./aiState";
import { useAiOperation } from "./aiOperation";
import { themeLabel } from "./themes";

export type AiPanelProps = { request?: DiscoveryRequest; aiAvailable?: boolean; t?: Translate };

type InsightPanelProps = AiPanelProps & {
  identity: InsightIdentity;
  metadata: InsightMetadata;
};

const sourceKinds: Record<string, string> = { wikipedia: "Wikipedia", openlibrary: "Open Library", opf: "EPUB metadata", model: "Model" };

export function Citations({ sources, t }: { sources: Insight["sources"]; t: Translate }) {
  if (!sources.length) return null;
  return (
    <details>
      <summary>{interpolate(t, "Sources ({count})", { count: sources.length })}</summary>
      <ul>
        {sources.map((source, index) => {
          const url = publicLink(source.url);
          return (
            <li key={index}>
              {url ? <a href={url} target="_blank" rel="noreferrer">{source.title}</a> : source.title}
              {" · "}{t(sourceKinds[source.kind] ?? source.kind)}
              {source.snippet && <p>{source.snippet}</p>}
            </li>
          );
        })}
      </ul>
    </details>
  );
}

function TextList({ title, values }: { title: string; values?: string[] }) {
  return values?.length ? (
    <section>
      <h4>{title}</h4>
      <ul>{values.map((value, index) => <li key={index}>{value}</li>)}</ul>
    </section>
  ) : null;
}

function InsightResult({ result, t }: { result: Insight; t: Translate }) {
  const data = result.payload;
  return (
    <div className="discovery-insight">
      {data.intro && <p>{data.intro}</p>}
      {data.author?.bio && <><h4>{t("Author")}</h4><p>{data.author.bio}</p></>}
      <TextList title={t("Notable works")} values={data.author?.notable_works} />
      {data.series && <><h4>{t("Series")}</h4><p>{data.series.name}{data.series.position != null && ` #${data.series.position}`}</p>{data.series.context && <p>{data.series.context}</p>}</>}
      {data.analysis && <><h4>{t("Analysis")}</h4><p>{data.analysis}</p></>}
      <TextList title={t("Content warnings")} values={data.content_warnings} />
      <TextList title={t("Themes")} values={data.themes?.map((theme) => themeLabel(theme, t))} />
      {data.theme_analysis && Object.entries(data.theme_analysis).map(([theme, explanation]) => (
        <div key={theme}><h4>{themeLabel(theme, t)}</h4><p>{explanation}</p></div>
      ))}
      {data.craft_notes && <><h4>{t("Craft notes")}</h4><p>{data.craft_notes}</p></>}
      {data.comparative_anchors?.length ? (
        <section>
          <h4>{t("Related works")}</h4>
          <ul>{data.comparative_anchors.map((item, index) => (
            <li key={index}><strong>{item.book} {interpolate(t, "by {author}", { author: item.author })}</strong><p>{item.similar_in}</p>{item.different_in && <p>{item.different_in}</p>}</li>
          ))}</ul>
        </section>
      ) : null}
      {data.distinctive_take && <><h4>{t("Perspective")}</h4><p>{data.distinctive_take}</p></>}
      <TextList title={t("Curiosities")} values={data.curiosities} />
      <TextList title={t("Discussion prompts")} values={data.discussion_prompts} />
      <Citations sources={result.sources ?? []} t={t} />
      <p>
        {interpolate(t, "Generated by {model} on {date}.", { model: result.model_id, date: new Date(result.generated_at).toLocaleDateString(document.documentElement.lang || undefined) })}
        {" "}{interpolate(t, "Prompt version {version}.", { version: result.prompt_version })}
        {data.confidence && ` ${interpolate(t, "Confidence: {level}.", { level: t(data.confidence) })}`}
      </p>
    </div>
  );
}

export function InsightPanel(props: InsightPanelProps) {
  return <EditionInsight key={JSON.stringify(insightIdentity(props.identity))} {...props} />;
}

function EditionInsight({ request, aiAvailable, identity, metadata, t = english }: InsightPanelProps) {
  const { settings, error: settingsError, loading } = useAiState(request, aiAvailable);
  const scope = JSON.stringify(insightIdentity(identity));
  const { run, busy, error, ambiguous, cancel, paid, recover } = useAiOperation(request, scope);
  const [result, setResult] = useState<Insight>();
  const [message, setMessage] = useState("");
  const [feedback, setFeedback] = useState("");
  const enabled = settings?.config.configured && settings.preferences.ai_enabled;
  const unavailable = settings ? missingProvider(settings.config, settings.preferences) : false;
  const styleKey = JSON.stringify(settings?.preferences.style);
  const providerId = settings?.preferences.provider_id;

  // `t` changes with the app language, which an `auto` insight is written in.
  useEffect(() => {
    setResult(undefined);
    setMessage("");
    setFeedback("");
  }, [request, enabled, styleKey, providerId, t]);

  if (!request || aiAvailable === false) return null;

  function load(action: "get" | "lookup" | "regenerate") {
    if (!request || !settings || !enabled || unavailable) return;
    const connection = request;
    const style = settings.preferences.style;
    const id = insightIdentity(identity);
    setMessage("");
    void run(async (signal) => {
      const get = async () => {
        if (id.content_hash) await promotePreview(connection, id).catch(() => undefined);
        return discoveryJson<Insight>(connection, "/ai/v1/insights/get", jsonBody("POST", { identity: id }, signal));
      };
      if (action !== "regenerate") {
        try {
          return await get();
        } catch (cause) {
          if (!isHttpStatus(cause, 404)) throw cause;
          if (action === "get") return undefined;
        }
      }
      const body: { identity: InsightIdentity; bundle: InsightMetadata; reason?: string } = {
        identity: id, bundle: insightBundle(metadata),
      };
      if (action === "regenerate") body.reason = feedback.trim();
      return discoveryJson<Insight>(connection, `/ai/v1/insights/${action}`, jsonBody("POST", body, signal));
    }, (value) => {
      if (!value) {
        setMessage("No saved insight was found for this edition and AI style.");
        return;
      }
      if (action === "get") recover(value.generated_at);
      rememberPreview(connection, id, style);
      setResult(value);
      if (action === "regenerate") setFeedback("");
    }, action !== "get" ? { previous: result?.generated_at } : undefined);
  }

  return (
    <section className="discovery-panel panel">
      <h3>{t("Book insights")}</h3>
      {loading && <p role="status">{t("Checking insight availability…")}</p>}
      {settingsError && <p role="alert">{translateRequestMessage(t, settingsError)} <button onClick={() => void refreshAiState(request)}>{t("Retry")}</button></p>}
      {settings && !enabled && <p>{t(settings.config.configured ? "Enable AI in Settings to open insights." : "AI is unavailable on this server.")}</p>}
      {enabled && unavailable && <p>{t("Select an available AI provider in Settings.")}</p>}
      {enabled && !unavailable && (
        <>
          <p>{t("Generating sends this edition’s book metadata to your configured AI service.")}</p>
          <div className="discovery-actions">
            <button disabled={busy} onClick={() => load("get")}>{t("Check saved insight")}</button>
            {!result && <button disabled={busy || ambiguous} onClick={() => load("lookup")}>{t("Get insight")}</button>}
            {busy && <button onClick={cancel}>{t(paid ? "Stop waiting" : "Cancel")}</button>}
          </div>
          {busy && <p role="status">{t("Loading insight…")}</p>}
          {message && <p role="status">{t(message)}</p>}
          {error && <p role="alert">{translateRequestMessage(t, error)}</p>}
          {result && (
            <>
              <InsightResult result={result} t={t} />
              <form onSubmit={(event) => { event.preventDefault(); load("regenerate"); }}>
                <label>
                  {t("Feedback for regeneration")}
                  <textarea value={feedback} maxLength={500} onChange={(event) => setFeedback(event.target.value)} />
                </label>
                <p>{t("Your feedback is sent to the AI provider. Leave private reading notes and annotations out of this field.")}</p>
                <button disabled={busy || ambiguous || !feedback.trim()}>{t("Regenerate insight")}</button>
              </form>
            </>
          )}
        </>
      )}
    </section>
  );
}
